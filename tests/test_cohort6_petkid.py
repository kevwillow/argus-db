@needs_raw
def test_every_promoted_uuid_is_byte_faithful_and_bounded():
    p = c6.build()
    scans = {v: c6.scan_uuids(v) for v in c6.APKS}
    vmap = {"Fi (Barking Labs Corp)": "fi", "Jiobit (Life360, Inc.)": "jiobit",
            "Whistle Labs, Inc. (Mars Petcare)": "whistle"}
    for cand in p["candidates"]:
        vend = vmap[cand["manufacturer"]]
        u = cand["identifier"]
        assert u in scans[vend], f"{u} not in {vend} dex"
        # excerpt is the verbatim dex byte-form (case preserved), <=200 chars
        assert cand["source_markers"]["byte_form"].lower() == u
        assert len(cand["source_markers"]["excerpt"]) <= c6.MAX_EXCERPT


@needs_raw
def test_all_promoted_are_net_new():
    p = c6.build()
    import sqlite3
    conn = sqlite3.connect(f"file:{c6.DB}?mode=ro", uri=True)
    for cand in p["candidates"] + [p["oui_candidate"]] + p["ble_local_name_bonus"]:
        assert cand["net_new"] is True, f"{cand['identifier']} not net-new"
        assert not c6.already_in_db(conn, cand["identifier"])
    conn.close()


