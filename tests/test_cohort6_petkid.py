"""MAC-411 — Cohort 6 (Pet / kid cellular tracker) extraction tests.

Proves candidates.json is regenerated byte-identical from the on-disk raw
artifacts (4 companion APKs + IEEE oui.csv), that every promoted UUID is
byte-faithful in its pinned dex + net-new in the live DB (mode=ro), that the
FP-triage is complete (every contested UUID has a cited co-located class), that
the hard guards hold (Tile cross-vendor; ble_company_id=0), and that §11 #7
(<=200-char excerpt) is app-enforced.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

from db.sources import cohort6_petkid as c6  # noqa: E402

RAW_PRESENT = all((REPO / a["rel_path"]).exists() for a in c6.APKS.values()) and \
    (REPO / c6.A_OUI).exists()
needs_raw = pytest.mark.skipif(not RAW_PRESENT, reason="gitignored raw APKs/registry not on disk")


# --- §11 #7 excerpt <=200 enforcement (positive + negative, no raw needed) -----
def test_clip_truncates_long():
    long = "x" * 500
    out = c6.clip(long)
    assert len(out) <= c6.MAX_EXCERPT
    assert out.endswith("…")


def test_clip_keeps_short():
    assert c6.clip("  short value  ") == "short value"


def test_source_row_key_deterministic():
    a = c6.source_row_key("u", "ble_service_uuid", "0000fa25-...")
    b = c6.source_row_key("u", "ble_service_uuid", "0000fa25-...")
    assert a == b and len(a) == 64


def test_person_pii_redaction():
    clean, n = c6.redact_person_pii("Contact John Smith at HQ")
    assert n == 1 and "[REDACTED_PERSON]" in clean
    clean0, n0 = c6.redact_person_pii("Whistle Labs, Inc., 251 Rhode Island Street")
    assert n0 == 0


